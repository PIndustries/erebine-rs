#!/usr/bin/env python3
"""Generate operation definitions from the reviewed catalog. No network required."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
ops=json.loads((root/'api/operations.json').read_text())['operations']
out=['// Generated by scripts/generate.py. Edit api/operations.json instead.','use crate::{Operation, Surface};']
for op in ops:
 name=op['name'].upper()
 out.append('/// '+op['method']+' '+op['path'])
 out.append('pub const '+name+': Operation = Operation { name: '+json.dumps(op['name'])+', method: '+json.dumps(op['method'])+', path: '+json.dumps(op['path'])+', surface: Surface::'+op['surface'].title()+', sources: &['+','.join(json.dumps(s) for s in op['sources'])+'] };')
out.append('pub const ALL: &[Operation] = &['+','.join(o['name'].upper() for o in ops)+'];')
# friendly aliases for the most common inference operations
for alias,name in [('MCP_POST','post_project_id_v1_mcp'),('MCP_GET','get_project_id_v1_mcp'),('MCP_DELETE','delete_project_id_v1_mcp'),('CHAT_COMPLETIONS_CREATE','post_project_id_endpoint_slug_v1_chat_completions'),('RESPONSES_CREATE','post_project_id_endpoint_slug_v1_responses'),('MODELS_LIST','get_project_id_endpoint_slug_v1_models'),('EMBEDDINGS_CREATE','post_project_id_endpoint_slug_v1_embeddings'),('FILES_CREATE','post_project_id_v1_files')]:
 out.append('pub const '+alias+': Operation = '+name.upper()+';')
(root/'src/operations.rs').write_text('\n'.join(out)+'\n')
import subprocess
subprocess.run(['rustfmt', '--edition', '2021', str(root/'src/operations.rs')], check=True)

# Generate a native method for every catalog binding. Project/routing parameters
# come from the configured Client; resource IDs are explicit method arguments.
api = ["// Generated by scripts/generate.py. Edit api/operations.json instead.",
       "use crate::{Client, Request, operations};",
       "#[derive(Clone, Copy)] pub struct Api<'a> { client: &'a Client }",
       "impl Client { pub fn api(&self) -> Api<'_> { Api { client: self } } }",
       "impl<'a> Api<'a> {"]
for op in ops:
    params = [p for p in op['parameters'] if p not in ['project_id', 'endpoint_slug']]
    arguments = ''.join(', '+p+': &str' for p in params)
    api.append('    /// '+op['method']+' '+op['path'])
    api.append('    pub fn '+op['name']+'(&self'+arguments+") -> Request<'a> {")
    api.append('        self.client.operation(operations::'+op['name'].upper()+')'+''.join('.param('+json.dumps(p)+', '+p+')' for p in params))
    api.append('    }')
api.append('}')
(root/'src/api.rs').write_text('\n'.join(api)+'\n')
subprocess.run(['rustfmt', '--edition', '2021', str(root/'src/api.rs')], check=True)
